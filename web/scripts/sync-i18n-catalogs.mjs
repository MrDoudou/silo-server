#!/usr/bin/env node

import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import { collectGoSourceMessages } from "./go-source-message-extractor.mjs";

const scriptPath = fileURLToPath(import.meta.url);
const webRoot = path.resolve(path.dirname(scriptPath), "..");
const repositoryRoot = path.resolve(webRoot, "..");
const englishPath = path.join(webRoot, "src", "i18n", "locales", "en.json");
const frenchPath = path.join(webRoot, "src", "i18n", "locales", "fr.json");
const generatedGoPath = path.join(
  repositoryRoot,
  "internal",
  "api",
  "handlers",
  "api_translation_keys_generated.go",
);

async function listFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const absolutePath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await listFiles(absolutePath)));
    else if (entry.isFile()) files.push(absolutePath);
  }

  return files;
}

function sortCatalog(value) {
  if (typeof value === "string") return value;
  return Object.fromEntries(
    Object.entries(value)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, child]) => [key, sortCatalog(child)]),
  );
}

function flattenCatalog(value, prefix = "", entries = new Map()) {
  for (const [name, child] of Object.entries(value)) {
    const key = prefix ? `${prefix}.${name}` : name;
    if (typeof child === "string") entries.set(key, child);
    else flattenCatalog(child, key, entries);
  }
  return entries;
}

function apiKeysByEnglishMessage(catalog) {
  const keys = new Map();
  for (const [key, message] of flattenCatalog(catalog)) {
    if (key.startsWith("api.") && !keys.has(message)) keys.set(message, key);
  }
  return keys;
}

function apiErrorKeysByCode(catalog) {
  const keys = new Map();
  for (const [key] of flattenCatalog(catalog)) {
    if (!key.startsWith("errors.api.")) continue;
    keys.set(key.slice("errors.api.".length), key);
  }
  return keys;
}

function renderGoLookup(keysByMessage, errorKeysByCode) {
  const entries = [...keysByMessage]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([message, key]) => `\t${JSON.stringify(message)}: ${JSON.stringify(key)},`)
    .join("\n");
  const errorEntries = [...errorKeysByCode]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([code, key]) => `\t${JSON.stringify(code)}: ${JSON.stringify(key)},`)
    .join("\n");

  return `// Code generated by web/scripts/sync-i18n-catalogs.mjs; DO NOT EDIT.\n\npackage handlers\n\nvar apiErrorTranslationKeys = map[string]string{\n${errorEntries}\n}\n\nvar apiMessageTranslationKeys = map[string]string{\n${entries}\n}\n\nfunc apiTranslationKey(code, message string) string {\n\tif key := apiErrorTranslationKeys[code]; key != "" {\n\t\treturn key\n\t}\n\treturn apiMessageTranslationKeys[message]\n}\n`;
}

async function collectBackendMessages() {
  const references = [];
  const roots = [
    path.join(repositoryRoot, "internal", "api"),
    path.join(repositoryRoot, "internal", "plugins"),
  ];

  for (const root of roots) {
    for (const absolutePath of await listFiles(root)) {
      if (!absolutePath.endsWith(".go") || absolutePath.endsWith("_test.go")) continue;
      if (absolutePath === generatedGoPath) continue;

      const relativePath = path.relative(repositoryRoot, absolutePath).split(path.sep).join("/");
      const source = await readFile(absolutePath, "utf8");
      references.push(...collectGoSourceMessages(relativePath, source));
    }
  }

  return references;
}

async function updateFile(filePath, expected, checkOnly) {
  let current = "";
  try {
    current = await readFile(filePath, "utf8");
  } catch {
    // A generated file may not exist on the first synchronization.
  }
  if (current === expected) return false;
  if (checkOnly) {
    throw new Error(`${path.relative(repositoryRoot, filePath)} is stale; run pnpm run i18n:sync`);
  }
  await writeFile(filePath, expected);
  return true;
}

async function main() {
  const checkOnly = process.argv.includes("--check");
  const english = sortCatalog(JSON.parse(await readFile(englishPath, "utf8")));
  const french = sortCatalog(JSON.parse(await readFile(frenchPath, "utf8")));
  const keysByMessage = apiKeysByEnglishMessage(english);
  const errorKeysByCode = apiErrorKeysByCode(english);
  const backendMessages = await collectBackendMessages();
  const missing = backendMessages.filter(({ value }) => !keysByMessage.has(value));

  if (missing.length) {
    const details = missing
      .slice(0, 30)
      .map(({ filePath, line, value }) => `${filePath}:${line}: ${JSON.stringify(value)}`)
      .join("\n");
    throw new Error(`${missing.length} backend messages have no api.* English key:\n${details}`);
  }

  const changed = [];
  if (await updateFile(englishPath, `${JSON.stringify(english, null, 2)}\n`, checkOnly)) {
    changed.push("en.json");
  }
  if (await updateFile(frenchPath, `${JSON.stringify(french, null, 2)}\n`, checkOnly)) {
    changed.push("fr.json");
  }
  if (
    await updateFile(generatedGoPath, renderGoLookup(keysByMessage, errorKeysByCode), checkOnly)
  ) {
    changed.push("api_translation_keys_generated.go");
  }

  console.log(
    `i18n catalogs ${checkOnly ? "verified" : changed.length ? `updated: ${changed.join(", ")}` : "unchanged"} (${flattenCatalog(english).size} English keys, ${keysByMessage.size} API messages).`,
  );
}

main().catch((error) => {
  console.error(`i18n catalog sync failed: ${error instanceof Error ? error.message : error}`);
  process.exitCode = 1;
});
